local was_suspended=true
while true do
    -- A user pause is owned by BizHawk/the user. Do not turn it into a
    -- checkpoint, issue native writes, or unpause it on the client's behalf.
    -- A modal dialog may suspend this whole coroutine; Python retains its
    -- single outstanding request until normal servicing resumes.
    if client.ispaused() and not checkpoint.frozen() then
        checkpoint.user_pause()
        pcall(overlay.draw,checkpoint.presentation(),false)
        emu.yield()
    else
    accept_or_receive()
    checkpoint.tick()
    if not checkpoint.frozen()and checkpoint.state.mode=='playing'then guarded(effects.tick)()end
    if not checkpoint.frozen() then
    if observe_only then
        if not observer_error then guarded(monitor.poll)() end
    else
        guarded(travel.poll)()
        if not travel.suspended() then
            if was_suspended then monitor.rebaseline() end
            guarded(monitor.poll)()
        end
        was_suspended=travel.suspended()
    end
    if not observe_only then guarded(checkpoint.process_delivery)() end
    end
    pcall(overlay.draw,checkpoint.presentation(),not checkpoint.frozen()and not client.ispaused())
    if (travel.state.blocked or delivery.state.blocked) and checkpoint.state.mode~='failed' then checkpoint.fail('Native controller blocked')end
    if checkpoint.frozen()or client.ispaused()then emu.yield() else emu.frameadvance()end
    end
end
