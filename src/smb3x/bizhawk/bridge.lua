local function reply(payload)
    if not peer then return end
    local data = json.encode(payload) .. "\n"
    peer:settimeout(0.1)
    local position = 1
    while position <= #data do
        local sent, err, last = peer:send(data, position)
        if sent then
            position = sent + 1
        elseif last and last >= position then
            position = last + 1
        else
            announce("SMB3 bridge send failed: " .. tostring(err), "Network", "Could not reply to the client. Check the client and diagnostic log.")
            peer:close()
            peer = nil
            checkpoint.disconnected()
            break
        end
    end
    if peer then peer:settimeout(0) end
end

local function sync_response(request)
    assert(not checkpoint.frozen()or checkpoint.waiting_for_bind()or checkpoint.state.effect_hold,'Native sync refused while checkpoint frozen')
    checkpoint.contact()
    local key = request.session
    if request.hazard_sha256~=build.hazards.sha256 or request.audiovisual_sha256~=build.audiovisual.sha256 or request.assignment_sha256~=build.level_shuffle.sha256 or request.type ~= "SYNC" or request.protocol ~= 40 or request.item_signature~=item_signature
        or request.location_signature~=location_signature
        or type(key) ~= "string" or not key:match("^[0-9a-f]+$") or #key ~= 64
        or type(request.commands) ~= "table" then
        return { protocol = 40, session = key, error = "Invalid bridge request" }
    end
    assert(key==build.session,"Wrong seed/slot for generated ROM")
    assert(request.goal==build.goal,"Seed-bound victory setting mismatch")
    for _,k in ipairs({'hammer_mode','star_hunt_mode','star_fragments_required','star_fragments_total','fortress_keys','reward_visual_style','inventory_mode'}) do
        assert(type(request.progression_config)=='table' and request.progression_config[k]==build.progression[k],'Seed-bound progression setting mismatch')
    end
    assert(request.rom_sha256==build.output.sha256 and request.patch_version==build.patch_version,"Native build identity mismatch")
    assert(type(request.native_authorized)=="boolean","Missing native journal authorization")
    monitor.configure(request.location_ids)
    if session == nil then
        if not observe_only then travel.bind(key) end
        session = key
        print("SMB3 bridge bound to AP session " .. key:sub(1, 12))
    elseif session ~= key then
        return { protocol = 40, session = key, error = "Different seed/slot: restart Lua and start a fresh game" }
    end

    if observe_only then
        return {protocol=40,session=key,checks=observer_error and {} or monitor.checks(),
            read_only=true,blocked=observer_error~=nil,acks={},lives=read8(A.lives),pending=#request.commands}
    end
    assert((read8(0x9F1B)%8>=4)==(build.progression.inventory_mode=='stacked'),'Native seed inventory setting mismatch')
    local same_instance=request.bridge_instance==bridge_instance
    local authorized=request.native_authorized and same_instance
    -- Readiness can freeze between backend polls. Return a read-only native
    -- snapshot so that the same watcher can service its durable effect commit.
    -- No inventory, progression or mailbox mutation is allowed during this gate.
    if not checkpoint.state.effect_hold then
    travel.authorize(authorized)
    if request.native_action and same_instance then travel.action(request.native_action) end
    travel.grant_pass(request.unlock_mask)
    travel.grant_progression(request.progression)
    checkpoint.prepare_sync(request.commands)
    if not checkpoint.frozen() and authorized and (request.unlock_mask==travel.state.unlock_mask) and travel.progression_ready() then
        delivery.sync(request.commands,request.handled,request.unlock_mask)
    end
    end
    local cosmetic_ok=false
    if authorized and request.presentation then pcall(overlay.snapshot,key,request.presentation) end
    if authorized then local ok,result=pcall(overlay.push,key,request.notifications or {});cosmetic_ok=ok and result end
    return {
        cosmetic_accepted=cosmetic_ok,
        save_requested=checkpoint.state.requested and checkpoint.batch_ready(),save_stable=checkpoint.state.stable,checkpoint_mode=checkpoint.state.mode,
        checkpoint_awaiting_ack=checkpoint.state.awaiting_ack,checkpoint_batch_count=checkpoint.state.batch_count,
        checkpoint_dirty=checkpoint.state.dirty,checkpoint_exposed=checkpoint.state.exposed,checkpoint_reason=checkpoint.state.reason,checkpoint_quit=checkpoint.state.quit,
        sync_ready=checkpoint.state.mode=='synchronizing' and checkpoint.state.stable>=30 and checkpoint.safe() and (#delivery.state.pending==0 or delivery.state.full_index~=nil),
        protocol = 40, session = key, checks = monitor.checks(),
        lives = read8(A.lives), pending = #delivery.state.pending,
        blocked = delivery.state.blocked or travel.state.phase=="blocked", acks = delivery.acks(),
        inventory=delivery.snapshot(),native=travel.native_status(),bridge_instance=bridge_instance,
        rom_sha256=build.output.sha256,patch_version=build.patch_version,unlock_mask=travel.state.unlock_mask
    }
end

local last_sequence=0
local last_request=nil
local last_response=nil
local function handle_line(line)
    local ok, request = pcall(json.decode, line)
    if not ok or type(request) ~= "table" then
        reply({protocol = 40, session = session, error = "Invalid JSON"})
        return
    end
    local success, response = pcall(function()
        assert(request.protocol==40 and request.session==build.session and request.run==control.run and request.token==control.token,'Transport run/session/owner mismatch')
        assert(type(request.sequence)=='number'and request.sequence==math.floor(request.sequence),'Invalid transport sequence')
        local challenge=request.resume_transport;request.resume_transport=nil
        local cached=request.sequence==last_sequence
        assert(cached or request.sequence==last_sequence+1,'Stale/skipped transport request')
        if cached then assert(last_request and checkpoint_module_equal(request,last_request),'Changed request at retained sequence')end
        if checkpoint.suspension()then
            if not challenge then
                if request.type=='CHECKPOINT'and(request.op=='STATUS'or request.op=='WAIT_SERVER')then
                    if cached then return last_response end
                    local value=checkpoint.control(request)
                    value.protocol=40;value.session=build.session;value.bridge_instance=bridge_instance;value.sequence=request.sequence
                    last_sequence=request.sequence;last_request=json.decode(json.encode(request));last_response=json.decode(json.encode(value))
                    return value
                end
                return {protocol=40,session=build.session,bridge_instance=bridge_instance,suspension=checkpoint.suspension()}
            end
            checkpoint.recover(challenge)
        end
        if cached then return last_response end
        local value
        if request.type=='CHECKPOINT' then
            assert(request.protocol==40,'Checkpoint protocol mismatch')
            value=checkpoint.control(request)
        else
            value=sync_response(request)
        end
        value.protocol=40;value.session=build.session;value.bridge_instance=bridge_instance;value.sequence=request.sequence
        last_sequence=request.sequence
        last_request=json.decode(json.encode(request));last_response=json.decode(json.encode(value))
        return value
    end)
    if success then
        reply(response)
    else
        checkpoint.fail(tostring(response))
        reply({protocol = 40, session = request.session, error = tostring(response)})
    end
end

local function accept_or_receive()
    if not peer then
        local accepted = server:accept()
        if accepted then
            peer = accepted
            peer:settimeout(0)
            receive_fragment = ""
            announce("SMB3 bridge: Python client connected", "Network", "SMB3X client connected.")
        end
        return
    end
    local line, err, partial = peer:receive()
    if line then
        handle_line(receive_fragment .. line)
        receive_fragment = ""
    elseif err == "timeout" then
        if partial and #partial > 0 then receive_fragment = receive_fragment .. partial end
        if #receive_fragment > 1048576 then
            announce("SMB3 bridge: oversized request discarded", "Network", "An oversized client request was refused. Check the client and diagnostic log.")
            checkpoint.disconnected()
            peer:close()
            peer = nil
            receive_fragment = ""
        end
    elseif err == "closed" then
        announce("SMB3 bridge: Python client disconnected; queued items retained", "Network", "SMB3X client disconnected; queued items are retained.")
        checkpoint.disconnected()
        peer:close()
        peer = nil
        receive_fragment = ""
    else
        announce("SMB3 bridge receive error: " .. tostring(err), "Network", "Client connection error. Check the client and diagnostic log.")
        checkpoint.disconnected()
        peer:close()
        peer = nil
        receive_fragment = ""
    end
end

